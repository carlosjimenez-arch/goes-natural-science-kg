class SequencingInput(Contract):
    schema_version: Literal["sequencing-input/1.0"] = "sequencing-input/1.0"
    graph: GraphSnapshot | EvidenceGraphSnapshot
    approval: Literal["approved", "provisional", "engineering-fixture"]
    reviewed_by: Text | None = None
    activities: tuple[LearningActivity, ...]
    key_micro_ids: References = ()
    contexts: tuple[LocalContext, ...] = ()
    continuity: tuple[ContinuityThread, ...] = ()

    @model_validator(mode="after")
    def integrity(self) -> Self:  # noqa: C901 - closed input references are validated together
        if self.approval == "approved" and not isinstance(self.graph, EvidenceGraphSnapshot):
            raise ValueError("approved builds require a chunk-traceable graph-snapshot/2.0")
        if self.approval == "approved" and not self.reviewed_by:
            raise ValueError("approved input requires an identified reviewer")
        micros = {m.id: m for m in self.graph.micro_skills}
        contexts = {c.id for c in self.contexts}
        acts = {a.id: a for a in self.activities}
        if len(acts) != len(self.activities) or len(contexts) != len(self.contexts):
            raise ValueError("duplicate activity or context IDs")
        if not set(self.key_micro_ids) <= set(micros):
            raise ValueError("unknown key micro-skill")
        for a in self.activities:
            if not set(a.micro_skill_ids) <= set(micros) or not set(a.context_tasks) <= contexts:
                raise ValueError("activity references unknown micro-skill or context")
            if len(set(a.allowed_grades)) != len(a.allowed_grades):
                raise ValueError("duplicate allowed grades")
            if a.kind == "teach" and a.minutes < sum(
                micros[k].estimated_minutes for k in a.micro_skill_ids
            ):
                raise ValueError("teaching activity underallocates estimated micro-skill minutes")
        for edge in self.graph.edges:
            if edge.type in (EdgeType.PREREQUISITE, EdgeType.CO_REQUISITE) and (
                edge.source not in micros or edge.target not in micros
            ):
                raise ValueError(
                    "resolve skill-level dependencies to micro-skills before scheduling"
                )
        for thread in self.continuity:
            if (
                thread.opening_activity_id not in acts
                or thread.continuation_activity_id not in acts
            ):
                raise ValueError("continuity thread references unknown activity")
        object.__setattr__(self, "activities", tuple(sorted(self.activities, key=lambda a: a.id)))
        object.__setattr__(self, "contexts", tuple(sorted(self.contexts, key=lambda c: c.id)))
        object.__setattr__(self, "continuity", tuple(sorted(self.continuity, key=lambda t: t.id)))
        return self



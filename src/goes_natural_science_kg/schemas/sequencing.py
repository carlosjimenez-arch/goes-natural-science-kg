class SequencingSettings(Contract):
    schema_version: Literal["sequencing-settings/1.0"] = "sequencing-settings/1.0"
    budget_hours: Annotated[int, Field(ge=1, le=400)] = 160
    seed: Annotated[int, Field(ge=0, le=2147483647)] = 42
    periods: Annotated[int, Field(ge=2, le=12)] = 4
    tolerance_percent: Literal[0] = 0
    knowing_max_percent: Annotated[int, Field(ge=0, le=100)] = 30
    reasoning_min_percent: dict[Grade, Annotated[int, Field(ge=0, le=100)]] = Field(
        default_factory=lambda: {2: 30, 3: 30, 4: 35, 5: 40, 6: 40}
    )
    domain_target_percent: dict[Text, Annotated[int, Field(ge=0, le=100)]] = Field(
        default_factory=lambda: {
            "physical-science": 34,
            "life-science": 33,
            "earth-space-science": 33,
        }
    )
    context_max_percent: Annotated[int, Field(ge=0, le=100)] = 60
    context_single_max_percent: Annotated[int, Field(ge=1, le=100)] = 25
    context_min_variety: Annotated[int, Field(ge=1)] = 3
    retrieval_target: Annotated[int, Field(ge=0, le=6)] = 2
    spacing_minutes: PositiveMinutes = 480
    max_deterministic_time: Annotated[float, Field(gt=0)] = 5.0
    weights: ObjectiveWeights = Field(default_factory=ObjectiveWeights)

    @model_validator(mode="after")
    def targets(self) -> Self:
        if set(self.reasoning_min_percent) != set(range(2, 7)):
            raise ValueError("reasoning targets required for every grade")
        if sum(self.domain_target_percent.values()) != 100:
            raise ValueError("domain targets must sum to 100 percent")
        return self


class ScheduledUnit(Contract):
    id: StableId
    activity_id: Slug
    micro_skill_ids: References
    kind: Literal["teach", "practice", "retrieval", "bridge", "assessment"]
    grade: Grade
    period: Annotated[int, Field(ge=0)]
    start_minute: Annotated[int, Field(ge=0)]
    end_minute: PositiveMinutes
    total_minutes: PositiveMinutes
    cognitive_domain: CognitiveDomain
    inquiry: bool
    theme: Slug
    task: Text
    mastery_criterion: Text
    context_id: Slug | None
    contexts: tuple[ContextTag, ...]

    @model_validator(mode="after")
    def duration(self) -> Self:
        if self.end_minute - self.start_minute != self.total_minutes:
            raise ValueError("unit interval and duration differ")
        if bool(self.context_id) != bool(self.contexts):
            raise ValueError("abstract units have no context tags")
        return self


class SolvedGradeCurriculum(Contract):
    schema_version: Literal["solved-grade-curriculum/1.0"] = "solved-grade-curriculum/1.0"
    grade: Grade
    approval: Literal["approved", "provisional", "engineering-fixture"]
    input_sha256: Digest
    settings_sha256: Digest
    total_minutes: PositiveMinutes
    budget_minutes: PositiveMinutes
    units: tuple[ScheduledUnit, ...]

    @model_validator(mode="after")
    def arithmetic(self) -> Self:
        if (
            self.total_minutes != self.budget_minutes
            or sum(u.total_minutes for u in self.units) != self.total_minutes
        ):
            raise ValueError("exact grade budget violated")
        previous = 0
        for u in self.units:
            if u.grade != self.grade or u.start_minute != previous:
                raise ValueError("units must form an ordered, gap-free grade calendar")
            previous = u.end_minute
        return self


